SELECT
    CAST(id AS VARCHAR) AS campaign_id,
    CAST(segment_id AS VARCHAR) AS segment_id,
    CAST(create_time AS VARCHAR) AS create_timestamp,
    CAST(send_time AS VARCHAR) AS send_timestamp,
    CAST(list_id AS VARCHAR) AS list_id,
    CAST(reply_to AS VARCHAR) AS reply_to_email,
    LOWER(TRIM(CAST(type AS VARCHAR))) AS campaign_type,
    CAST(title AS VARCHAR) AS title,
    CAST(archive_url AS VARCHAR) AS archive_url,
    LOWER(TRIM(CAST(authenticate AS VARCHAR))) AS authenticate,
    LOWER(TRIM(CAST(auto_footer AS VARCHAR))) AS auto_footer,
    LOWER(TRIM(CAST(auto_tweet AS VARCHAR))) AS auto_tweet,
    CAST(clicktale AS VARCHAR) AS clicktale,
    CAST(content_type AS VARCHAR) AS content_type,
    LOWER(TRIM(CAST(drag_and_drop AS VARCHAR))) AS drag_and_drop,
    LOWER(TRIM(CAST(fb_comments AS VARCHAR))) AS fb_comments,
    CAST(from_name AS VARCHAR) AS from_name,
    CAST(google_analytics AS VARCHAR) AS google_analytics,
    LOWER(TRIM(CAST(inline_css AS VARCHAR))) AS inline_css,
    CAST(long_archive_url AS VARCHAR) AS long_archive_url,
    LOWER(TRIM(CAST(status AS VARCHAR))) AS status,
    CAST(subject_line AS VARCHAR) AS subject_line,
    CAST(template_id AS VARCHAR) AS template_id,
    LOWER(TRIM(CAST(timewarp AS VARCHAR))) AS timewarp,
    CAST(to_name AS VARCHAR) AS to_name,
    LOWER(TRIM(CAST(track_ecomm_360 AS VARCHAR))) AS track_ecomm_360,
    LOWER(TRIM(CAST(track_goals AS VARCHAR))) AS track_goals,
    LOWER(TRIM(CAST(track_html_clicks AS VARCHAR))) AS track_html_clicks,
    LOWER(TRIM(CAST(track_opens AS VARCHAR))) AS track_opens,
    LOWER(TRIM(CAST(track_text_clicks AS VARCHAR))) AS track_text_clicks,
    LOWER(TRIM(CAST(use_conversation AS VARCHAR))) AS use_conversation
FROM {{ source('raw', 'campaign') }}
